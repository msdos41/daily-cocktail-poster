#!/usr/bin/env node
// Regenerates src/data/cocktailDates.ts from git history.
// publishedAt = first commit that added the cocktail's stable entry (`id: "<slug>"`) in src/data/cocktails.ts
// updatedAt   = latest commit (git blame -w) touching any line of that cocktail's blocks in
//               src/data/cocktails.ts and src/data/cocktailEditorial.ts.
// Dates are YYYY-MM-DD in Asia/Shanghai. The committed output file is the source of truth;
// builds never call git. Usage: node scripts/sync-cocktail-dates.mjs (requires full history).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const FILES = ["src/data/cocktails.ts", "src/data/cocktailEditorial.ts"];
const OUT = "src/data/cocktailDates.ts";
const git = (...args) => execFileSync("git", args, { encoding: "utf8", maxBuffer: 64 << 20 });
const toDay = (epoch) =>
  new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Shanghai", year: "numeric", month: "2-digit", day: "2-digit" })
    .format(new Date(epoch * 1000));

const src = readFileSync(FILES[0], "utf8").split("\n");
const slugs = [...src.join("\n").matchAll(/^    id: "([a-z0-9-]+)",$/gm)].map((m) => m[1]);

function blocks(lines, slug) {
  const ranges = [];
  lines.forEach((line, i) => {
    let start = -1;
    if (line === `    id: "${slug}",` && /^  \{$/.test(lines[i - 1])) start = i - 1;
    const m = line.match(/^(\s+)"?([a-z0-9-]+)"?: \{$/);
    if (m && m[2] === slug) start = i;
    if (start < 0) return;
    const indent = lines[start].match(/^\s*/)[0];
    let end = start + 1;
    while (end < lines.length && !lines[end].startsWith(`${indent}}`)) end++;
    ranges.push([start + 1, end + 1]);
  });
  return ranges;
}

function blameMax(file, ranges) {
  if (!ranges.length) return 0;
  const args = ["blame", "-w", "--line-porcelain", ...ranges.flatMap(([a, b]) => ["-L", `${a},${b}`]), "--", file];
  return Math.max(...[...git(...args).matchAll(/^author-time (\d+)$/gm)].map((m) => Number(m[1])));
}

const result = {};
for (const slug of slugs) {
  const added = git("log", "--reverse", "--format=%at", `-S    id: "${slug}",`, "--", FILES[0]).trim().split("\n")[0];
  let updated = 0;
  for (const file of FILES) updated = Math.max(updated, blameMax(file, blocks(readFileSync(file, "utf8").split("\n"), slug)));
  const pub = Number(added);
  result[slug] = { publishedAt: toDay(pub), updatedAt: toDay(Math.max(pub, updated)) };
}

const body = `// Generated by scripts/sync-cocktail-dates.mjs from git history. Committed data is the source of truth.
// Dates are YYYY-MM-DD in Asia/Shanghai.
export type CocktailDates = { publishedAt: string; updatedAt: string };

export const cocktailDates: Record<string, CocktailDates> = {
${slugs.map((s) => `  "${s}": { publishedAt: "${result[s].publishedAt}", updatedAt: "${result[s].updatedAt}" },`).join("\n")}
};
`;
writeFileSync(OUT, body);
console.log(`Wrote ${slugs.length} cocktails to ${OUT}`);
